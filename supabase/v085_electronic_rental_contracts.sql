-- ReChair OMS v0.8.5
-- Secure electronic rental contracts for personal and commercial rentals.
-- Run after v083_rental_retrieval_inventory.sql.

create extension if not exists pgcrypto;

create table if not exists public.rental_contracts (
  id uuid primary key default gen_random_uuid(),
  consultation_id uuid not null references public.consultations(id) on delete cascade,
  version integer not null default 1 check (version > 0),
  contract_no text not null unique,
  contract_type text not null check (contract_type in ('personal','commercial')),
  status text not null default 'draft'
    check (status in ('draft','sent','signed','superseded','void')),
  document_snapshot jsonb not null default '{}'::jsonb,
  document_sha256 text not null,
  terms_version text not null default '2026-08-v1',
  access_token_hash text unique,
  access_expires_at timestamptz,
  phone_verification_failures integer not null default 0 check (phone_verification_failures >= 0),
  phone_locked_until timestamptz,
  phone_verified_at timestamptz,
  signature_path text,
  signer_name text,
  contract_consent boolean not null default false,
  privacy_consent boolean not null default false,
  sent_at timestamptz,
  signed_at timestamptz,
  superseded_at timestamptz,
  voided_at timestamptz,
  void_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (consultation_id, version)
);

create table if not exists public.rental_contract_events (
  id bigint generated by default as identity primary key,
  contract_id uuid not null references public.rental_contracts(id) on delete cascade,
  consultation_id uuid not null references public.consultations(id) on delete cascade,
  event_type text not null,
  actor_type text not null check (actor_type in ('admin','customer','system')),
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.consultations
  add column if not exists rental_contract_id uuid references public.rental_contracts(id);

alter table public.consultations
  add column if not exists rental_contract_version integer;

alter table public.consultations
  add column if not exists rental_contract_document_hash text;

create index if not exists rental_contracts_consultation_created_idx
  on public.rental_contracts(consultation_id, created_at desc);

create index if not exists rental_contracts_status_idx
  on public.rental_contracts(status, updated_at desc);

create unique index if not exists rental_contracts_one_open_draft_idx
  on public.rental_contracts(consultation_id)
  where status in ('draft','sent');

create index if not exists rental_contract_events_contract_idx
  on public.rental_contract_events(contract_id, created_at);

alter table public.rental_contracts enable row level security;
alter table public.rental_contract_events enable row level security;
revoke all on table public.rental_contracts from anon, authenticated;
revoke all on table public.rental_contract_events from anon, authenticated;

insert into storage.buckets (id, name, public)
values ('rental-contract-signatures', 'rental-contract-signatures', false)
